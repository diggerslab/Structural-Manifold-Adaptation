import copy
import json
from pathlib import Path
import unittest
import numpy as np
from sma import SMASampler, StructuralMetric, build_graph
from sma.demo import synthetic_dataset
from sma.math import coverage_coefficients, diffusion_kernel


class CoreTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.episodes, cls.arrays, cls.visual = synthetic_dataset()
        cls.graph, _ = build_graph(cls.arrays, cls.visual)
        cls.initial = np.linspace(0.4, 1.6, len(cls.graph['region_tasks']))

    def sampler(self, **kwargs):
        g = self.graph
        return SMASampler(self.episodes, g['windows'], g['regions'], g['region_tasks'],
                          g['K'], self.initial, priority_eligible=g['priority_eligible'], **kwargs)

    def test_reference_golden(self):
        """Compare outputs generated by the original research code, not by SMA."""
        expected = json.loads((Path(__file__).parent / 'fixtures/reference.json').read_text())
        for key, values in expected['graph'].items():
            np.testing.assert_allclose(self.graph[key], values, atol=1e-11, rtol=1e-10)
        s = self.sampler()
        for step, row in enumerate(expected['rounds']):
            ticket = s.draw()
            for key, values in row['draw'].items():
                np.testing.assert_allclose(ticket[key], values, atol=1e-12)
            regions = np.asarray(ticket['region_ids'])
            loss = self.initial[regions] * (0.7 + 0.05 * step + 0.1 * (regions % 3))
            s.observe(ticket, loss, np.ones(len(regions)), (step + 1) * 5.)
            update = s.update_sampler((step + 1) * 5.)
            for key, values in row['update'].items():
                np.testing.assert_allclose(update[key], values, atol=1e-11, rtol=1e-10)

    def test_resume_json_roundtrip(self):
        s = self.sampler()
        for i in range(3):
            d = s.draw()
            s.observe(d, np.ones(64), np.ones(64), i + 1.)
            s.update_sampler(i + 1.)
        restored = self.sampler(state=json.loads(json.dumps(s.state_dict())))
        for _ in range(10):
            self.assertEqual(s.draw(), restored.draw())

    def test_mixture_and_task_bounds(self):
        s = self.sampler()
        for step in range(20):
            d = s.draw()
            self.assertEqual(sum(d['branch']), 32)
            self.assertTrue(np.all(np.asarray(d['probability']) > 0))
            scores = np.where(np.asarray(d['region_ids']) < 2, 100., 0.01)
            s.observe(d, scores, np.ones(64), step + 1.)
            p = np.asarray(s.update_sampler(step + 1.)['task_probability'])
            self.assertAlmostEqual(p.sum(), 1.)
            self.assertTrue(np.all((p >= .05 - 1e-10) & (p <= .2 + 1e-10)))

    def test_energy_marginal_is_exact(self):
        rng = np.random.default_rng(8)
        p, q = rng.dirichlet(np.ones(4)), rng.dirichlet(np.ones(4))
        _, K = diffusion_kernel(np.ones((4, 4)) - np.eye(4))
        eta = 1 / 2048
        c, marginal = coverage_coefficients(p, q, K)
        energy = lambda x: (x - q) @ K @ (x - q)
        brute = [energy(p) - energy((1 - eta) * p + eta * e) for e in np.eye(4)]
        np.testing.assert_allclose(marginal, brute, atol=1e-15)
        self.assertAlmostEqual(q @ c, 1.)

    def test_graph_barriers(self):
        g = self.graph
        centers = g['representative_window_ids']
        task = self.arrays['tasks'][centers]
        phase = self.arrays['phase'][centers]
        forbidden = (task[:, None] != task[None, :]) | (phase[:, None] != phase[None, :])
        self.assertTrue(np.all(g['W'][forbidden] == 0))
        np.testing.assert_allclose(g['K'], g['K'].T, atol=1e-12)
        self.assertGreater(np.linalg.eigvalsh(g['K']).min(), 0)

    def test_mask_and_quaternion_sign(self):
        a = copy.deepcopy(self.arrays)
        before = StructuralMetric(a, self.visual).distance([0, 10], [1, 11], barrier=False)
        a['quat'] *= -1
        a['actions'][~a['mask']] = 9999
        after = StructuralMetric(a, self.visual).distance([0, 10], [1, 11], barrier=False)
        np.testing.assert_allclose(before, after, atol=1e-10)

    def test_stale_residual_resets(self):
        s = self.sampler()
        d = s.draw()
        s.observe(d, np.full(64, 100), np.ones(64), 1.)
        np.testing.assert_array_equal(s.update_sampler(182.)['r'], np.ones(s.n))

    def test_bad_inputs_rejected(self):
        with self.assertRaises(ValueError):
            self.sampler(global_batch_size=63)
        with self.assertRaises(ValueError):
            self.sampler(method='unknown')
        s = self.sampler()
        state = s.state_dict()
        state['fingerprint'] = 'wrong'
        with self.assertRaises(ValueError):
            self.sampler(state=state)
        d = s.draw()
        with self.assertRaises(ValueError):
            s.observe(d, np.ones(64), np.zeros(64), 1.)
        with self.assertRaises(ValueError):
            s.update_sampler(-1.)

    def test_nontraining_data_rejected(self):
        episodes = copy.deepcopy(self.episodes)
        episodes[0]['split'] = 'test'
        g = self.graph
        with self.assertRaisesRegex(ValueError, 'training episodes'):
            SMASampler(episodes, g['windows'], g['regions'], g['region_tasks'], g['K'], self.initial)

    def test_ticket_score_order_is_checked(self):
        s = self.sampler()
        d = s.draw()
        d['region_ids'][0] = (d['region_ids'][0] + 1) % s.n
        with self.assertRaises(ValueError):
            s.observe(d, np.ones(64), np.ones(64), 1.)

    def test_report_can_be_serialized(self):
        _, report = build_graph(self.arrays, self.visual)
        self.assertGreater(len(json.dumps(report)), 0)

    def test_uniform_control(self):
        s = self.sampler(method='U')
        d = s.draw()
        self.assertEqual(sum(d['branch']), 0)
        np.testing.assert_array_equal(d['probability'], s.uniform_window[d['window_ids']])

    def test_task_ids_and_batch_are_portable(self):
        eps, arrays, visual = synthetic_dataset(task_ids=(3, 17))
        g, _ = build_graph(arrays, visual)
        s = SMASampler(eps, g['windows'], g['regions'], g['region_tasks'], g['K'],
                       np.ones(len(g['region_tasks'])), global_batch_size=8,
                       priority_eligible=g['priority_eligible'])
        d = s.draw()
        self.assertEqual(len(d['window_ids']), 8)
        self.assertEqual(sum(d['branch']), 4)
        np.testing.assert_allclose(s.update_sampler(0)['task_probability'], [.5, .5])


if __name__ == '__main__':
    unittest.main()
